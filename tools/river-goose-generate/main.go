// Command river-goose-generate generates goose SQL migrations containing
// River's embedded migrations, so that River's schema can be applied with
// goose instead of River's own migrator.
//
// It inspects the migrations directory to find the latest generated river
// migration, creates a new goose migration file for every missing river
// version, and fills it with the SQL from the river library (the same SQL that
// `river migrate-get` prints). No database connection, `river` or `goose`
// binary is required.
//
// Statements containing dollar-quoted strings (for example `$$ ... $$`
// PL/pgSQL function bodies) are wrapped in goose's
// `-- +goose StatementBegin`/`-- +goose StatementEnd` annotations, because
// goose's parser otherwise ends a statement at the first line ending with a
// semicolon and would truncate such bodies.
//
// Usage (from the repository root):
//
//	go run ./tools/river-goose-generate [-dir DIR] [-exclude VERSIONS]
package main

import (
	"cmp"
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime/debug"
	"slices"
	"strconv"
	"strings"

	"github.com/riverqueue/river/riverdriver"
	"github.com/riverqueue/river/riverdriver/riverpgxv5"
	"github.com/riverqueue/river/rivermigrate"
	"github.com/riverqueue/river/rivershared/sqlctemplate"
)

const riverModulePath = "github.com/riverqueue/river"

var (
	// Goose migration files are named `{version}_{name}.sql` with sequential
	// numbering (5 digits). River migrations generated by this tool are
	// additionally named `river_{riverVersion}`.
	gooseFileRe = regexp.MustCompile(`^(\d{5})_.+\.sql$`)
	riverFileRe = regexp.MustCompile(`^(\d{5})_river_(\d+)\.sql$`)
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "river-goose-generate: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	var (
		dir = flag.String(
			"dir",
			"internal/impl/database/migrations",
			"goose migrations directory",
		)
		exclude = flag.String(
			"exclude",
			"",
			"comma-separated river migration versions to skip (e.g. 1)",
		)
	)
	flag.Parse()

	excluded, err := parseVersions(*exclude)
	if err != nil {
		return err
	}

	migrator, err := rivermigrate.New(riverpgxv5.New(nil), nil)
	if err != nil {
		return fmt.Errorf("error creating river migrator: %w", err)
	}
	allVersions := migrator.AllVersions()
	if len(allVersions) == 0 {
		return fmt.Errorf("river library has no migrations")
	}

	state, err := scanDir(*dir)
	if err != nil {
		return err
	}

	riverVersion := moduleVersion()
	created := 0

	for _, migration := range allVersions {
		if state.riverVersions[migration.Version] || excluded[migration.Version] {
			continue
		}

		filename := fmt.Sprintf("%05d_river_%03d.sql", state.nextSeq(), migration.Version)
		path := filepath.Join(*dir, filename)

		content, err := renderMigration(migration, riverVersion)
		if err != nil {
			return fmt.Errorf("error rendering river migration %d: %w", migration.Version, err)
		}

		if err := os.WriteFile(path, content, 0o644); err != nil {
			return fmt.Errorf("error writing %s: %w", path, err)
		}

		fmt.Printf("Created new file: %s\n", path)
		created++
	}

	if err := warnUnknownVersions(allVersions, state.riverVersions); err != nil {
		return err
	}

	if err := checkRiverOrder(*dir); err != nil {
		return err
	}

	if created == 0 {
		fmt.Printf("Nothing to do, %s is up to date with river %s (versions 1-%d)\n",
			*dir, riverVersion, allVersions[len(allVersions)-1].Version)
	} else {
		fmt.Printf("Created %d migration(s) matching river %s\n", created, riverVersion)
	}

	return nil
}

// dirState is the state of a goose migrations directory: the river versions
// that already have a migration file, and the highest goose version in use.
type dirState struct {
	riverVersions map[int]bool
	maxSeq        int
}

// nextSeq returns the next sequential goose version number, incrementing with
// every call so files created in the same run never collide.
func (s *dirState) nextSeq() int {
	s.maxSeq++
	return s.maxSeq
}

func scanDir(dir string) (*dirState, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("error reading migrations directory %s: %w", dir, err)
	}

	state := &dirState{riverVersions: make(map[int]bool)}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}

		if m := riverFileRe.FindStringSubmatch(entry.Name()); m != nil {
			seq, _ := strconv.Atoi(m[1])
			version, _ := strconv.Atoi(m[2])
			state.riverVersions[version] = true
			state.maxSeq = max(state.maxSeq, seq)
		} else if m := gooseFileRe.FindStringSubmatch(entry.Name()); m != nil {
			seq, _ := strconv.Atoi(m[1])
			state.maxSeq = max(state.maxSeq, seq)
		}
	}

	return state, nil
}

func renderMigration(migration rivermigrate.Migration, riverVersion string) ([]byte, error) {
	var b strings.Builder

	fmt.Fprintf(
		&b,
		"-- Code generated by tools/river-goose-generate from river %s; DO NOT EDIT.\n\n",
		riverVersion,
	)

	fmt.Fprintf(&b, "-- +goose Up\n")
	fmt.Fprintf(
		&b,
		"-- River %s migration %03d [up]\n",
		riverdriver.MigrationLineMain,
		migration.Version,
	)
	upSQL, err := renderSQL(migration.SQLUp)
	if err != nil {
		return nil, err
	}
	upSQL, err = wrapDollarQuotedStatements(upSQL)
	if err != nil {
		return nil, fmt.Errorf(
			"error wrapping dollar-quoted statements in river migration %d [up]: %w",
			migration.Version, err,
		)
	}
	b.WriteString(upSQL)
	b.WriteString("\n\n")

	fmt.Fprintf(&b, "-- +goose Down\n")
	fmt.Fprintf(
		&b,
		"-- River %s migration %03d [down]\n",
		riverdriver.MigrationLineMain,
		migration.Version,
	)
	downSQL, err := renderSQL(migration.SQLDown)
	if err != nil {
		return nil, err
	}
	downSQL, err = wrapDollarQuotedStatements(downSQL)
	if err != nil {
		return nil, fmt.Errorf(
			"error wrapping dollar-quoted statements in river migration %d [down]: %w",
			migration.Version, err,
		)
	}
	b.WriteString(downSQL)
	b.WriteString("\n")

	return []byte(b.String()), nil
}

// renderSQL replaces SQL templates (e.g. `/* TEMPLATE: schema */`) the same way
// the river migrator does. Migrations run through goose with the default
// search_path, so the schema prefix is empty.
func renderSQL(sql string) (string, error) {
	if !strings.Contains(sql, "/* TEMPLATE") {
		return strings.TrimSpace(sql), nil
	}

	ctx := sqlctemplate.WithReplacements(context.Background(), map[string]sqlctemplate.Replacement{
		"schema": {Value: ""},
	}, nil)

	rendered, _, err := (&sqlctemplate.Replacer{}).RunSafely(ctx, "$", sql, nil)
	if err != nil {
		return "", fmt.Errorf("error rendering SQL templates: %w", err)
	}
	return strings.TrimSpace(rendered), nil
}

const (
	gooseStatementBegin = "-- +goose StatementBegin"
	gooseStatementEnd   = "-- +goose StatementEnd"
)

// wrapDollarQuotedStatements wraps statements containing dollar-quoted strings
// (for example `$$ ... $$` PL/pgSQL function bodies) in goose's
// StatementBegin/StatementEnd annotations.
//
// Goose's parser is line-based: outside of these annotations it ends a
// statement at the first line ending with a semicolon and does not understand
// dollar quotes, so a function body would be truncated at the first semicolon
// inside it.
func wrapDollarQuotedStatements(sql string) (string, error) {
	lines := strings.Split(sql, "\n")
	out := make([]string, 0, len(lines)+2)

	var (
		scanner   statementScanner
		open      bool // a StatementBegin is open for the current statement
		stmtStart = -1 // index in out of the current statement's first line
	)

	for _, line := range lines {
		info, err := scanner.scanLine(line)
		if err != nil {
			return "", err
		}

		if info.content && stmtStart == -1 {
			stmtStart = len(out)
		}

		if info.quoteOpen && !open {
			if stmtStart < 0 {
				return "", fmt.Errorf("statement start not found before %q", line)
			}
			out = insertString(out, stmtStart, gooseStatementBegin)
			open = true
			stmtStart = -1
		}

		out = append(out, line)

		if info.stmtEnd && open {
			out = append(out, gooseStatementEnd)
			open = false
		}
		if info.stmtEnd {
			stmtStart = -1
		}
	}

	if scanner.dollarClose != "" {
		return "", fmt.Errorf("unterminated dollar-quoted string %q", scanner.dollarClose)
	}
	if open {
		return "", fmt.Errorf("statement missing a terminating semicolon")
	}

	return strings.Join(out, "\n"), nil
}

// statementScanner tracks quote and comment state while scanning the lines of
// a SQL migration section.
type statementScanner struct {
	dollarClose string // closing tag while inside a dollar-quoted string
	inString    bool   // inside a single-quoted string
	inComment   bool   // inside a /* block comment */
}

// lineInfo describes what a scanned line means for goose's statement parser.
type lineInfo struct {
	content   bool // line goose buffers as part of a statement
	stmtEnd   bool // line ends a statement with a top-level semicolon
	quoteOpen bool // a dollar-quoted string starts on this line
	afterEnd  bool // a statement already ended earlier on this line
}

// scanLine scans a single line of SQL and reports where the line ends a
// statement or starts a dollar-quoted string.
func (s *statementScanner) scanLine(line string) (lineInfo, error) {
	var info lineInfo

	for i := 0; i < len(line); {
		next, err := s.scan(line, i, &info)
		if err != nil {
			return info, err
		}
		i = next
	}

	trimmed := strings.TrimSpace(line)
	info.content = trimmed != "" && !strings.HasPrefix(trimmed, "--")
	return info, nil
}

// scan scans line from position i according to the current state and returns
// the next position to scan from.
func (s *statementScanner) scan(line string, i int, info *lineInfo) (int, error) {
	switch {
	case s.dollarClose != "":
		return s.scanDollarClose(line, i), nil
	case s.inComment:
		return s.scanBlockComment(line, i), nil
	case s.inString:
		return s.scanInString(line, i), nil
	default:
		return s.scanToken(line, i, info)
	}
}

// scanDollarClose scans inside a dollar-quoted string, which only ends at its
// closing tag.
func (s *statementScanner) scanDollarClose(line string, i int) int {
	closing := s.dollarClose
	idx := strings.Index(line[i:], closing)
	if idx < 0 {
		return len(line)
	}
	s.dollarClose = ""
	return i + idx + len(closing)
}

// scanBlockComment scans inside a /* block comment */, up to and including its
// terminator if it is on this line.
func (s *statementScanner) scanBlockComment(line string, i int) int {
	end := strings.Index(line[i:], "*/")
	if end < 0 {
		return len(line)
	}
	s.inComment = false
	return i + end + 2
}

// scanInString scans inside a single-quoted string, where ” is an escaped
// quote, up to and including the closing quote if it is on this line.
func (s *statementScanner) scanInString(line string, i int) int {
	for j := i; j < len(line); j++ {
		if line[j] != '\'' {
			continue
		}
		if j+1 < len(line) && line[j+1] == '\'' {
			j++ // escaped quote; the post statement skips the second one
			continue
		}
		s.inString = false
		return j + 1
	}
	return len(line)
}

// scanToken scans one token outside of strings, comments, and dollar-quoted
// strings.
func (s *statementScanner) scanToken(line string, i int, info *lineInfo) (int, error) {
	rest := line[i:]
	switch rest[0] {
	case '\'':
		s.inString = true
		return i + 1, nil
	case '-':
		if strings.HasPrefix(rest, "--") {
			return len(line), nil // the rest of the line is a comment
		}
	case '/':
		if strings.HasPrefix(rest, "/*") {
			s.inComment = true
			return i + 2, nil
		}
	case '$':
		return s.scanDollarOpen(line, i, info)
	case ';':
		info.stmtEnd = true
		info.afterEnd = true
		return i + 1, nil
	}
	return i + 1, nil
}

// scanDollarOpen scans a `$` that may start a dollar-quoted string.
func (s *statementScanner) scanDollarOpen(line string, i int, info *lineInfo) (int, error) {
	tag, ok := dollarQuoteTag(line[i:])
	if !ok {
		return i + 1, nil
	}
	if info.afterEnd {
		return i, fmt.Errorf("statement starting mid-line is not supported: %q", line)
	}
	info.quoteOpen = true
	s.dollarClose = tag
	return i + len(tag), nil
}

// dollarQuoteTag returns the dollar-quoted string token starting at the
// beginning of s, i.e. `$$` or `$tag$`, and whether s starts with one.
// Placeholders like `$1` are not dollar quotes.
func dollarQuoteTag(s string) (string, bool) {
	if len(s) < 2 || s[0] != '$' {
		return "", false
	}
	end := strings.IndexByte(s[1:], '$')
	if end < 0 {
		return "", false
	}
	tag := s[1 : end+1]
	for i := 0; i < len(tag); i++ {
		c := tag[i]
		alpha := c == '_' || ('a' <= c && c <= 'z') || ('A' <= c && c <= 'Z')
		digit := '0' <= c && c <= '9'
		if alpha || (i > 0 && digit) {
			continue
		}
		return "", false
	}
	return s[:end+2], true
}

// insertString inserts s into lines at index i.
func insertString(lines []string, i int, s string) []string {
	lines = append(lines, "")
	copy(lines[i+1:], lines[i:])
	lines[i] = s
	return lines
}

// warnUnknownVersions warns about river migration files in the directory that
// don't exist in the river library, which can happen if the river dependency
// is downgraded.
func warnUnknownVersions(allVersions []rivermigrate.Migration, riverVersions map[int]bool) error {
	known := make(map[int]bool, len(allVersions))
	for _, migration := range allVersions {
		known[migration.Version] = true
	}

	var unknown []int
	for version := range riverVersions {
		if !known[version] {
			unknown = append(unknown, version)
		}
	}
	slices.Sort(unknown)

	if len(unknown) > 0 {
		return fmt.Errorf(
			"river migration file(s) with unknown version(s) %v found, check the river dependency version",
			unknown,
		)
	}
	return nil
}

// riverMigrationFile is a river migration file found in the migrations
// directory: its goose sequence number and the river version it contains.
type riverMigrationFile struct {
	seq     int
	version int
}

// checkRiverOrder verifies that river migration files, sorted by their goose
// sequence number, follow river's version order, because goose applies
// migrations by sequence number. The order can get out of sync when a river
// migration file is deleted and regenerated with a fresh sequence number, or
// when a previously excluded river version is generated after newer versions.
func checkRiverOrder(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("error reading migrations directory %s: %w", dir, err)
	}

	var files []riverMigrationFile
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		if m := riverFileRe.FindStringSubmatch(entry.Name()); m != nil {
			seq, _ := strconv.Atoi(m[1])
			version, _ := strconv.Atoi(m[2])
			files = append(files, riverMigrationFile{seq: seq, version: version})
		}
	}

	slices.SortFunc(files, func(a, b riverMigrationFile) int {
		return cmp.Compare(a.seq, b.seq)
	})

	for i := 1; i < len(files); i++ {
		if files[i].version <= files[i-1].version {
			return fmt.Errorf(
				"river migration files are out of order: %s (river version %d) comes before %s (river version %d); goose applies migrations by sequence number, so restore the original sequence number(s)",
				riverFileName(files[i-1]),
				files[i-1].version,
				riverFileName(files[i]),
				files[i].version,
			)
		}
	}
	return nil
}

// riverFileName returns the goose file name for a river migration file.
func riverFileName(f riverMigrationFile) string {
	return fmt.Sprintf("%05d_river_%03d.sql", f.seq, f.version)
}

func parseVersions(s string) (map[int]bool, error) {
	versions := make(map[int]bool)
	if s == "" {
		return versions, nil
	}

	for _, part := range strings.Split(s, ",") {
		version, err := strconv.Atoi(strings.TrimSpace(part))
		if err != nil {
			return nil, fmt.Errorf("error parsing excluded version %q: %w", part, err)
		}
		versions[version] = true
	}
	return versions, nil
}

func moduleVersion() string {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return "unknown"
	}
	for _, dep := range info.Deps {
		if dep.Path == riverModulePath {
			return dep.Version
		}
	}
	return "unknown"
}
